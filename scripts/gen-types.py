#!/usr/bin/env python3
"""Generate src/types/database.ts from the locally migrated schema (Supabase-style `Database` type).

Used because `supabase gen types` needs the Docker-based stack. Introspects information_schema and
pg_proc of the throwaway local database built by scripts/db-local.sh. Usage:
  python3 scripts/gen-types.py > src/types/database.ts
"""
import json
import os
import subprocess

DB = os.environ.get("LOCAL_DB", "seedx_test")
PSQL = ["psql", "-h", os.environ.get("LOCAL_PGHOST", "/tmp"), "-p", os.environ.get("LOCAL_PGPORT", "54329"), "-U", "postgres", "-d", DB, "-At", "-c"]

TS = {
    "uuid": "string", "text": "string", "character varying": "string", "date": "string", "timestamp with time zone": "string",
    "boolean": "boolean", "smallint": "number", "integer": "number", "bigint": "number", "numeric": "number",
    "jsonb": "Json", "json": "Json", "ARRAY": "string[]", "USER-DEFINED": "string",
}


def q(sql):
    return json.loads(subprocess.check_output(PSQL + [sql]).decode() or "[]")


cols = q("""select coalesce(json_agg(c order by table_name, ordinal_position), '[]') from (
  select c.table_name, c.column_name, c.ordinal_position, c.data_type, c.is_nullable = 'YES' as nullable,
         (c.column_default is not null or c.is_identity = 'YES' or c.is_generated = 'ALWAYS') as has_default
    from information_schema.columns c join information_schema.tables t using (table_schema, table_name)
   where c.table_schema = 'public' and t.table_type = 'BASE TABLE') c""")
fns = q("""select coalesce(json_agg(f order by name), '[]') from (
  select p.proname as name, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f') f""")

tables = {}
for c in cols:
    tables.setdefault(c["table_name"], []).append(c)


def ts_type(c):
    t = TS.get(c["data_type"], "unknown")
    return f"{t} | null" if c["nullable"] else t


out = ["// GENERATED by scripts/gen-types.py from the migrated schema. Do not edit by hand.",
       "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]", "",
       "export type Database = {", "  public: {", "    Tables: {"]
for name, cs in sorted(tables.items()):
    out.append(f"      {name}: {{")
    out.append("        Row: {")
    out += [f"          {c['column_name']}: {ts_type(c)}" for c in cs]
    out.append("        }")
    out.append("        Insert: {")
    out += [f"          {c['column_name']}{'?' if c['nullable'] or c['has_default'] else ''}: {ts_type(c)}" for c in cs]
    out.append("        }")
    out.append("        Update: {")
    out += [f"          {c['column_name']}?: {ts_type(c)}" for c in cs]
    out.append("        }")
    out.append("        Relationships: []")
    out.append("      }")
out += ["    }", "    Views: { [_ in never]: never }", "    Functions: {"]


def arg_type(pgtype):
    pgtype = pgtype.strip()
    base = pgtype.split(" DEFAULT ")[0].strip()
    m = {"uuid": "string", "text": "string", "numeric": "number", "bigint": "number", "integer": "number", "date": "string",
         "jsonb": "Json", "uuid[]": "string[]", "boolean": "boolean"}
    return m.get(base, "unknown"), " DEFAULT " in pgtype


for f in fns:
    args = []
    if f["args"]:
        for a in f["args"].split(", "):
            parts = a.split(" ", 1)
            t, opt = arg_type(parts[1])
            args.append(f"{parts[0]}{'?' if opt else ''}: {t}")
    res = f["result"]
    rt = "Json" if res.startswith("TABLE") or res in ("jsonb",) else (
        "number" if res == "integer" else "string" if res == "uuid" else "undefined" if res == "void" else "Json")
    args_ts = "{ " + "; ".join(args) + " }" if args else "Record<PropertyKey, never>"
    out.append(f"      {f['name']}: {{ Args: {args_ts}; Returns: {rt} }}")
out += ["    }", "    Enums: { [_ in never]: never }", "    CompositeTypes: { [_ in never]: never }", "  }", "}", "",
        "type PublicTables = Database['public']['Tables']",
        "export type Tables<T extends keyof PublicTables> = PublicTables[T]['Row']",
        "export type TablesInsert<T extends keyof PublicTables> = PublicTables[T]['Insert']",
        "export type TablesUpdate<T extends keyof PublicTables> = PublicTables[T]['Update']", ""]
print("\n".join(out))
