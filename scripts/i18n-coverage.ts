// Generates docs/i18n-coverage.md: per-language key coverage against English, plus missing keys by namespace.
// Run: npx tsx scripts/i18n-coverage.ts
import { writeFileSync } from 'node:fs'
import { resources } from '../src/i18n/resources'
import { LANGUAGES } from '../src/i18n/languages'

type Tree = { [k: string]: string | Tree }
function flatten(o: Tree, prefix = ''): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [k, v] of Object.entries(o)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (typeof v === 'string') out[key] = v
    else Object.assign(out, flatten(v, key))
  }
  return out
}

const en = flatten(resources.en.translation as unknown as Tree)
const enKeys = Object.keys(en)
const namespaces = [...new Set(enKeys.map((k) => k.split('.')[0]))]
const lines: string[] = [
  '# i18n coverage report', '',
  `Generated by \`scripts/i18n-coverage.ts\` on ${new Date().toISOString().slice(0, 10)}. English is the source (${enKeys.length} keys).`,
  'Missing keys fall back to English at runtime, key by key. All non-English text is machine-assisted and needs native-speaker review before production use.', '',
  '| Language | Code | Translated keys | Coverage | Namespaces fully translated |', '|---|---|---:|---:|---|',
]
const missingByLang: Record<string, Record<string, string[]>> = {}
for (const l of LANGUAGES) {
  const flat = flatten((resources as Record<string, { translation: unknown }>)[l.code].translation as Tree)
  const have = enKeys.filter((k) => typeof flat[k] === 'string' && (flat[k].trim() !== '' || en[k] === ''))
  const missing = enKeys.filter((k) => !have.includes(k))
  const full = namespaces.filter((ns) => !missing.some((k) => k.startsWith(`${ns}.`)))
  missingByLang[l.code] = {}
  for (const k of missing) (missingByLang[l.code][k.split('.')[0]] ??= []).push(k)
  lines.push(`| ${l.native} (${l.english}) | ${l.code} | ${have.length} / ${enKeys.length} | ${((have.length / enKeys.length) * 100).toFixed(1)}% | ${full.length} / ${namespaces.length} |`)
}
lines.push('', '## Missing keys by namespace (falls back to English)', '')
for (const l of LANGUAGES) {
  const m = missingByLang[l.code]
  const entries = Object.entries(m)
  if (!entries.length) continue
  lines.push(`### ${l.english} (${l.code})`, '', entries.map(([ns, keys]) => `- \`${ns}\`: ${keys.length} missing`).join('\n'), '')
}
writeFileSync(new URL('../docs/i18n-coverage.md', import.meta.url), lines.join('\n') + '\n')
console.log(lines.slice(5, 7 + LANGUAGES.length).join('\n'))
